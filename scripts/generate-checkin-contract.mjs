import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const raw = await fs.readFile(path.join(root, 'shared/checkin-contract.json'), 'utf8');
const contract = JSON.parse(raw);
for (const key of ['statuses', 'successStatuses', 'recoverableStatuses', 'immediateRetryStatuses', 'manualHandoffStatuses', 'availabilityKinds']) {
  if (!Array.isArray(contract[key]) || new Set(contract[key]).size !== contract[key].length
    || contract[key].some(value => !/^[a-z_]+$/.test(value))) throw new Error('Invalid status contract');
}
for (const key of ['successStatuses', 'recoverableStatuses', 'immediateRetryStatuses', 'manualHandoffStatuses']) {
  if (contract[key].some(value => !contract.statuses.includes(value))) throw new Error('Unknown contract status');
}
const hash = createHash('sha256').update(raw).digest('hex');
const js = `// Generated by scripts/generate-checkin-contract.mjs; do not edit.\n// sha256: ${hash}\nexport const CHECKIN_CONTRACT = Object.freeze(${JSON.stringify(contract, null, 2)});\n`;
const ps = `# Generated by scripts/generate-checkin-contract.mjs; do not edit.\n# sha256: ${hash}\n` +
  Object.entries({statuses:'Statuses', successStatuses:'SuccessStatuses', recoverableStatuses:'RecoverableStatuses', immediateRetryStatuses:'ImmediateRetryStatuses', manualHandoffStatuses:'ManualHandoffStatuses', availabilityKinds:'AvailabilityKinds'})
    .map(([key, label]) => `$script:Checkin${label} = @(${contract[key].map(value => `'${value}'`).join(', ')})\n`).join('') +
  '$script:CheckinFailureCategories = @{\n' + Object.entries(contract.failureCodes).map(([key,value]) => `    '${key}' = '${value}'\n`).join('') + '}\n';
let drift = false;
for (const [file, contents] of [['src/checkin-contract.generated.mjs', js], ['scripts/CheckinContract.generated.ps1', ps]]) {
  if (process.argv.includes('--check')) {
    if (await fs.readFile(path.join(root, file), 'utf8').catch(() => '') !== contents) { console.error(`Contract drift: ${file}`); drift = true; }
  } else await fs.writeFile(path.join(root, file), contents);
}
if (drift) process.exitCode = 1;
