export function matchGdGiantGlyph(rows) {
  if (!Array.isArray(rows) || rows.length < 8 || rows.length > 14
    || Array.from(rows).some(row => typeof row !== 'string' || !/^[01]{3,12}$/.test(row)
      || row.length !== rows[0].length)) return { code: '', confidence: 0, score: 0, margin: 0 };
  const ranked = Object.entries(GD_GIANT_FONT_TEMPLATES).map(([code, template]) => ({
    code, score: scorePixelFontTemplate(rows, template),
  })).sort((a, b) => b.score - a.score);
  const best = ranked[0], margin = best.score - ranked[1].score;
  const accepted = best.score >= 0.92 && margin >= 0.06;
  return { code: accepted ? best.code : '', confidence: accepted ? Math.floor(best.score * 100) : 0, score: best.score, margin };
}

// Split the cleaned natural pixels by empty columns, preserving every stroke.
// Six distinct glyphs and six unambiguous font matches are required.
export function recognizeGdGiantText(data, width, height) {
  const unavailable = { code: null, confidence: 0, fontDetected: false, method: 'gd_giant_template' };
  if (!(data instanceof Uint8Array) || !Number.isInteger(width) || !Number.isInteger(height)
    || width < 1 || height < 1 || data.length !== width * height || data.length > 1000000) return unavailable;
  const runs = [];
  for (let x = 0; x < width; x++) {
    let top = height, bottom = -1;
    for (let y = 0; y < height; y++) if (data[y * width + x] < 128) { top = Math.min(top, y); bottom = y; }
    if (bottom < 0) continue;
    const previous = runs.at(-1);
    if (previous && previous.right === x - 1) { previous.right = x; previous.top = Math.min(previous.top, top); previous.bottom = Math.max(previous.bottom, bottom); }
    else runs.push({ left: x, right: x, top, bottom });
  }
  if (runs.length !== 6) return unavailable;
  const glyphs = runs.map(run => matchGdGiantGlyph(Array.from({ length: run.bottom - run.top + 1 }, (_, dy) => (
    Array.from({ length: run.right - run.left + 1 }, (_, dx) => data[(run.top + dy) * width + run.left + dx] < 128 ? '1' : '0').join('')
  ))));
  const fontDetected = glyphs.filter(glyph => glyph.code).length >= 4;
  if (glyphs.some(glyph => !glyph.code)) return { ...unavailable, fontDetected };
  return { code: glyphs.map(glyph => glyph.code).join(''), confidence: Math.min(...glyphs.map(glyph => glyph.confidence)),
    fontDetected: true, method: 'gd_giant_template' };
}
