function parseGrid(rows) {
  return rows.map((row) => [...row].map((value) => value === "1" ? 1 : 0));
}

function shiftedDiceScore(observed, template, offsetX, offsetY) {
  let observedInk = 0;
  let templateInk = 0;
  let intersection = 0;
  for (let y = 0; y < observed.length; y += 1) {
    for (let x = 0; x < observed[y].length; x += 1) {
      if (!observed[y][x]) continue;
      observedInk += 1;
      const templateY = y + offsetY;
      const templateX = x + offsetX;
      if (template[templateY]?.[templateX]) intersection += 1;
    }
  }
  for (const row of template) templateInk += row.reduce((sum, value) => sum + value, 0);
  if (observedInk === 0 || templateInk === 0) return 0;
  return (2 * intersection) / (observedInk + templateInk);
}

export function scorePixelFontTemplate(observedRows, templateRows) {
  const observed = parseGrid(observedRows);
  const template = parseGrid(templateRows);
  let best = 0;
  for (let offsetY = -1; offsetY <= 1; offsetY += 1) {
    for (let offsetX = -1; offsetX <= 1; offsetX += 1) {
      best = Math.max(best, shiftedDiceScore(observed, template, offsetX, offsetY));
    }
  }
  return best;
}

export function matchPixelFontGlyph(observedRows, { minimumScore = 0.82, minimumMargin = 0.06 } = {}) {
  const ranked = Object.entries(PIXEL_FONT_TEMPLATES).map(([code, rows]) => ({
    code,
    score: Math.max(
      scorePixelFontTemplate(observedRows, rows),
      ...(PIXEL_FONT_TEMPLATE_VARIANTS[code] ?? []).map((variant) => (
        scorePixelFontTemplate(observedRows, variant)
      )),
    ),
  })).sort((left, right) => right.score - left.score || left.code.localeCompare(right.code));
  const best = ranked[0] ?? { code: "", score: 0 };
  const second = ranked[1] ?? { code: "", score: 0 };
  const margin = best.score - second.score;
  const exactCanonicalO = best.code === "O" && best.score >= 0.999;
  if (best.score < minimumScore || (margin < minimumMargin && !exactCanonicalO)) {
    return {
      code: "",
      confidence: 0,
      score: best.score,
      margin,
      bestCode: best.code,
      secondCode: second.code,
    };
  }
  return {
    code: best.code,
    confidence: Math.round(best.score * 100),
    score: best.score,
    margin,
    bestCode: best.code,
    secondCode: second.code,
  };
}
